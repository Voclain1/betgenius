/**
 * Banker curation rules (planBankerCuration in src/lib/geniusCuration.ts),
 * checked without a database.
 *
 * Run: npx tsx scripts/check-banker-curation.ts
 */
export {};

const react = require("react");
react.cache = (fn: any) => fn;

import {
  BANKER_CONFIDENCE_FLOOR,
  BANKER_INTENT_PROVENANCE,
  BANKER_MAX_PICKS,
  VIP_GENERATED_PROVENANCE,
  planBankerCuration,
  type CurationRow,
} from "../src/lib/geniusCuration";

let failures = 0;
function check(name: string, ok: boolean) {
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}`);
  if (!ok) failures++;
}

const NOW = new Date("2026-10-21T12:00:00.000Z");
const LATER = new Date("2026-10-21T20:00:00.000Z");
const EARLIER = new Date("2026-10-21T11:00:00.000Z");

let team = 1000;
function row(id: string, over: Partial<CurationRow> = {}): CurationRow {
  const home = team++;
  const away = team++;
  return {
    id,
    leagueApiId: 39,
    confidence: 80,
    provenance: "STANDARD_CURATED",
    marketType: "MATCH_WINNER",
    createdAt: new Date("2026-10-20T10:00:00.000Z"),
    kickoff: LATER,
    fixtureApiId: home * 10,
    homeTeamApiId: home,
    awayTeamApiId: away,
    categories: ["FEATURED"],
    ...over,
  };
}

// Highest confidence wins, from any feed and any competition, up to the cap.
{
  const rows = [
    row("ucl", { leagueApiId: 2, confidence: 86, categories: ["VIP", "FEATURED"] }),
    row("latvia", { leagueApiId: 365, confidence: 84, categories: ["GENIUS"] }),
    row("epl", { leagueApiId: 39, confidence: 81 }),
    ...Array.from({ length: BANKER_MAX_PICKS }, (_, i) => row(`filler${i}`, { confidence: 76 })),
  ];
  const plan = planBankerCuration(rows, NOW);
  check("the highest confidence picks lead, from any feed", JSON.stringify(plan.selectedIds.slice(0, 3)) === JSON.stringify(["ucl", "latvia", "epl"]));
  check(`never more than ${BANKER_MAX_PICKS}`, plan.selectedIds.length === BANKER_MAX_PICKS);
  check("the daily cap allows a good day of five to seven", BANKER_MAX_PICKS === 7);
}

// Competition priority only breaks ties.
{
  const rows = [row("minor", { leagueApiId: 365, confidence: 82 }), row("uel", { leagueApiId: 3, confidence: 82 })];
  check("a confidence tie goes to the bigger competition", planBankerCuration(rows, NOW).selectedIds[0] === "uel");
}

// Floor, doubles, paid-only and one per fixture.
{
  const shared = { fixtureApiId: 1, homeTeamApiId: 1, awayTeamApiId: 2 };
  const rows = [
    row("weak", { confidence: BANKER_CONFIDENCE_FLOOR - 1 }),
    row("double", { marketType: "SAME_GAME_DOUBLE", confidence: 95 }),
    row("paidOnly", { provenance: VIP_GENERATED_PROVENANCE, confidence: 95, categories: ["VIP"] }),
    row("sameA", { ...shared, confidence: 90 }),
    row("sameB", { ...shared, confidence: 88, marketType: "BTTS" }),
  ];
  const plan = planBankerCuration(rows, NOW);
  check("below the floor is never a banker", !plan.selectedIds.includes("weak"));
  check("a same-game double is never a banker", !plan.selectedIds.includes("double"));
  check("a paid-only pick is never shown free as a banker", !plan.selectedIds.includes("paidOnly"));
  check("one banker per fixture, the stronger one", plan.selectedIds.includes("sameA") && !plan.selectedIds.includes("sameB"));
  check("a thin day gets fewer bankers, not weaker ones", plan.selectedIds.length === 1);
}

// Fixed points.
{
  const rows = [
    row("startedWeak", { kickoff: EARLIER, confidence: 76, categories: ["FEATURED", "BANKER"] }),
    ...Array.from({ length: BANKER_MAX_PICKS }, (_, i) => row(`strong${i}`, { confidence: 90 - i })),
  ];
  const plan = planBankerCuration(rows, NOW);
  check("a banker that has kicked off is kept", plan.selectedIds.includes("startedWeak") && !plan.removed.includes("startedWeak"));
  check("a kept banker uses a slot", plan.selectedIds.length === BANKER_MAX_PICKS && !plan.selectedIds.includes(`strong${BANKER_MAX_PICKS - 1}`));
}
{
  const rows = [
    row("oldPass", { provenance: BANKER_INTENT_PROVENANCE, confidence: 70, categories: ["BANKER"] }),
    row("onlyBanker", { confidence: 72, categories: ["BANKER"] }),
    row("strong", { confidence: 90 }),
  ];
  const plan = planBankerCuration(rows, NOW);
  check("a banker generated by the old pass is kept", plan.selectedIds.includes("oldPass"));
  check("a row whose only feed is Banker is never untagged", plan.selectedIds.includes("onlyBanker"));
}
{
  const rows = [
    row("earlyPick", { confidence: 78, categories: ["FEATURED", "BANKER"] }),
    ...Array.from({ length: BANKER_MAX_PICKS }, (_, i) => row(`s${i}`, { confidence: 90 - i })),
  ];
  const plan = planBankerCuration(rows, NOW);
  check("before kickoff a stronger pick replaces a weaker banker", plan.removed.includes("earlyPick") && plan.added.length === BANKER_MAX_PICKS);
  check("a match that has kicked off is never newly added", !planBankerCuration([row("late", { kickoff: EARLIER, confidence: 95 })], NOW).selectedIds.length);
}

if (failures) {
  console.error(`\n${failures} check(s) failed`);
  process.exit(1);
}
console.log("\nAll Banker curation checks passed");
